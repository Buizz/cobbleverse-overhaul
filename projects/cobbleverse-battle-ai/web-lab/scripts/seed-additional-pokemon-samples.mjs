function completeStats(values = {}, fallback = 0) {
  return Object.fromEntries(stats.map((stat) => [stat, values[stat] ?? fallback]));
}

function buildSample(entry) {
  const champions = entry.path.startsWith("champions/");
  return {
    schemaVersion: 1,
    id: entry.id,
    source: champions ? "pkmnchamps" : "pokesample",
    format: champions ? "champions" : "sv",
    battleStyle: "single",
    title: entry.title,
    species: entry.species[0],
    speciesLabel: entry.species[1],
    level: 50,
    ability: entry.ability[0],
    abilityLabel: entry.ability[1],
    heldItem: entry.item[0],
    heldItemLabel: entry.item[1],
    nature: entry.nature[0],
    natureLabel: entry.nature[1],
    tera: entry.tera ?? "",
    moves: entry.moves.map(([move]) => move),
    moveLabels: entry.moves.map(([, label]) => label),
    ivs: completeStats(entry.ivs, 31),
    evs: completeStats(entry.evs),
    ...(champions
      ? { sourceStats: { system: "champions-normalized" } }
      : {}),
    tags: entry.tags,
    sourceUrl: champions ? championsSource : svSource,
  };
}

for (const entry of additions) {
  const output = path.join(root, entry.path);
  await mkdir(path.dirname(output), { recursive: true });
  await writeFile(output, `${JSON.stringify(buildSample(entry), null, 2)}\n`);
}

const indexPath = path.join(root, "index.json");
const index = JSON.parse(await readFile(indexPath, "utf8"));
index.samples = [...new Set([...index.samples, ...additions.map((entry) => entry.path)])];
index.updatedAt = "2026-07-30";
await writeFile(indexPath, `${JSON.stringify(index, null, 2)}\n`);

